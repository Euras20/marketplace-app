    public function run(): void
    {
        $store = Store::where('code', 'agri')->first()
            ?? Store::where('status', 'active')->orderBy('id')->first();

        if (!$store) {
            $this->command->error('No active store found.');
            return;
        }

        $sort = 0;
        foreach ($this->attributes as $label) {
            $code = Str::slug($label, '_');
            if (strlen($code) > 60) {
                $code = substr($code, 0, 60);
            }
            if ($code === '') {
                continue;
            }

            ProductAttributeDefinition::updateOrCreate(
                [
                    'store_id' => $store->id,
                    'code' => $code,
                ],
                [
                    'label' => $label,
                    'data_type' => 'text',
                    'is_required' => false,
                    'is_filterable' => false,
                    'sort_order' => $sort++,
                ]
            );
        }

        $this->command->info(count($this->attributes) . " attribute definitions seeded for store: {$store->code}");
    }
