    public function run(): void
    {
        $store = Store::where('code', 'agri')->first()
            ?? Store::where('status', 'active')->orderBy('id')->first();

        if (!$store) {
            $this->command->error('No active store found. Seed stores first.');
            return;
        }

        foreach ($this->brands as $name) {
            Brand::updateOrCreate(
                [
                    'store_id' => $store->id,
                    'slug' => Str::slug($name),
                ],
                [
                    'name' => $name,
                    'is_active' => true,
                ]
            );
        }

        $this->command->info(count($this->brands) . " brands seeded for store: {$store->code}");
    }
